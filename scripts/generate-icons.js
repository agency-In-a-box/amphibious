#!/usr/bin/env node
/**
 * Generates src/js/icon-set.generated.ts, the inline SVG map behind
 * `data-lucide` / createIcon().
 *
 * The set is every icon the library always ships (src/icons/core-icons.json)
 * plus src/icons/demo-icons.json (names demo pages build in JavaScript, which
 * the scan cannot see) plus every name used in a `data-lucide` attribute in the deployable HTML
 * pages or in src/**\/*.ts. SVGs come from the `lucide-static` dev dependency;
 * brand marks Lucide no longer ships live in src/icons/brands/. An unknown name
 * fails the build instead of rendering a placeholder.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUTPUT = join(root, 'src/js/icon-set.generated.ts');

const SCAN_DIRS = ['docs', 'examples', 'demos', 'src'];
const SCAN_FILES = ['index.html', 'sitemap.html'];
const SKIP_DIRS = new Set(['_archive', 'node_modules']);
const ICON_ATTR = /data-lucide=["']([a-z0-9][a-z0-9-]*)["']/g;

function walk(dir, exts) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (!SKIP_DIRS.has(entry.name)) out.push(...walk(join(dir, entry.name), exts));
    } else if (exts.some((ext) => entry.name.endsWith(ext))) {
      out.push(join(dir, entry.name));
    }
  }
  return out;
}

/** Map of icon name to the files that reference it. */
export function collectUsedIcons() {
  const files = [
    ...SCAN_FILES.map((file) => join(root, file)),
    ...SCAN_DIRS.flatMap((dir) => walk(join(root, dir), ['.html', '.ts'])),
  ];
  const used = new Map();
  for (const file of files) {
    for (const [, name] of readFileSync(file, 'utf8').matchAll(ICON_ATTR)) {
      if (!used.has(name)) used.set(name, new Set());
      used.get(name).add(relative(root, file));
    }
  }
  return used;
}

function readSvg(name) {
  for (const path of [
    join(root, 'src/icons/brands', `${name}.svg`),
    join(root, 'node_modules/lucide-static/icons', `${name}.svg`),
  ]) {
    try {
      return readFileSync(path, 'utf8');
    } catch {
      // try the next source
    }
  }
  return null;
}

function normalize(svg) {
  return svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\sclass="[^"]*"/, '')
    .replace(/\s+/g, ' ')
    .replace(/> </g, '><')
    .replace(/ \/>/g, '/>')
    .replace(/" >/g, '">')
    .replace(/<svg /, '<svg ')
    .trim();
}

export function buildIconSource() {
  const core = JSON.parse(readFileSync(join(root, 'src/icons/core-icons.json'), 'utf8'));
  const demo = JSON.parse(readFileSync(join(root, 'src/icons/demo-icons.json'), 'utf8'));
  const used = collectUsedIcons();
  const names = [...new Set([...core, ...demo, ...used.keys()])].sort();

  const unknown = names.filter((name) => readSvg(name) === null);
  if (unknown.length > 0) {
    const detail = unknown
      .map((name) => `  ${name}: ${[...(used.get(name) ?? ['core-icons.json'])].join(', ')}`)
      .join('\n');
    throw new Error(`Unknown icon name(s); not in lucide-static or src/icons/brands:\n${detail}`);
  }

  const entries = names.map((name) => `  '${name}': '${normalize(readSvg(name))}',`);
  return `// Generated by scripts/generate-icons.js. Do not edit; run \`bun run generate:icons\`.
export const iconSVGs: Record<string, string> = {
${entries.join('\n')}
};
`;
}

export function generateIcons() {
  const source = buildIconSource();
  writeFileSync(OUTPUT, source);
  return source;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    const source = generateIcons();
    console.log(`Wrote ${relative(root, OUTPUT)} (${(source.length / 1024).toFixed(1)} KB)`);
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
}
